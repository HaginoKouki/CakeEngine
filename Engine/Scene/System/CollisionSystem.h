/*====================================
 *
 * シーン内のコライダー同士の重なりを調べ、結果を各コライダーへ書き戻す。
 * 球（SphereCollider）と直方体（BoxCollider）を扱い、
 * 球×球 / 球×箱 / 箱×箱 の3通りすべてを判定する。
 *
 * 【形の違いはここで吸収する】
 * 集める段で ColliderEntry という共通の形へ潰してから総当たりに入る。
 * コライダーの種類を増やすときは、集める関数と Intersect の分岐を足すだけでよく、
 * ループ側は触らない。
 *
 * 【箱は向き付き（OBB）】
 * ワールド行列から軸と半長を取り出すため、回転・スケールがそのまま効く。
 * ギズモに描かれる枠と判定範囲が一致する。
 * 球は radius をワールド単位でそのまま使う（スケールが効かない）ので、扱いが違う。
 *
 * 【総当たり（O(n²)）】
 * 数百個までなら十分間に合うので空間分割は入れていない。
 * ただし箱同士は分離軸を15本調べる必要があるため、
 * その手前で「形を包む球」による早期棄却を挟み、届かない組はSATに入れない。
 *
 * 【呼ぶ場所】
 * ワールド行列が確定した後、つまり Scene::UpdateTransforms の直後。
 * 前に呼ぶと1フレーム前の位置で判定することになる。
 *
 * 【非アクティブは参加しない】
 * SetActive(false) のオブジェクトは無視する。弾をプールで使い回す前提。
 *
 * 【押し戻しはしない】
 * 重なりを hits に記録するだけ。位置の修正は読んだ側の仕事。
 *
 * ====================================*/
